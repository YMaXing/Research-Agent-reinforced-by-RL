def _load_section_oracle(article: str, use_averaged: bool = False) -> dict:
    """Load and validate section_oracle.json (v2+) for *article*.

    ``use_averaged=True`` loads the sibling ``section_oracle_averaged.json``
    (written by merge_replicate_oracles.py) instead -- its own "version" field
    numbers the merge format, not the section_oracle.json schema, so the v2+
    check is skipped for it.
    """
    fname = "section_oracle_averaged.json" if use_averaged else "section_oracle.json"
    path = _BASES_DIR / article / fname
    if not path.exists():
        raise FileNotFoundError(f"{fname} not found for '{article}'")
    data = json.loads(path.read_text(encoding="utf-8"))
    if not use_averaged:
        v = data.get("version", 1)
        if v < 2:
            raise ValueError(
                f"section_oracle.json for '{article}' is version {v}; "
                "version 2+ required. Re-run generate_episode_oracles.py."
            )
    if not data.get("sections"):
        raise ValueError(f"{fname} for '{article}' has no sections.")
    return data


def _load_guideline_features(article: str) -> dict:
    """Load guideline_features.json for *article*."""
    path = _BASES_DIR / article / "guideline_features.json"
    return json.loads(path.read_text(encoding="utf-8"))


# ---------------------------------------------------------------------------
# R_w  (target-words-weighted mean of per-arm section rewards)
# ---------------------------------------------------------------------------

def _compute_r_w(
    oracle_sections: dict[str, dict],
    features_sections: dict[str, dict],
) -> tuple[dict[str, float], int, int, int]:
    """Return (r_w_per_arm, total_target_words, n_sections, n_with_target).

    oracle_sections  : section_oracle.json["sections"]  {sec_id: {oracle, rewards, explore?}}
    features_sections: guideline_features.json["sections"]  {sec_id: {target_words, …}}

    As of section_oracle.json version 4, each section may carry an "explore"
    sub-dict (per-arm) alongside "rewards" (per-arm, unchanged full total).
    When present, this function aggregates the two pieces DIFFERENTLY:
      - "rewards - explore" (i.e. gt_base + user_intent + cost) is averaged
        target-words-weighted, as before -- a section assigned a bigger word
        budget legitimately deserves more say over the article's overall
        content-quality/adherence/cost verdict.
      - "explore" is averaged with a SIMPLE (unweighted) mean across sections
        -- a genuinely valuable enhancement instance shouldn't count for more
        or less just because it happened to land in a long vs short section.
        See run13_rl_grok_pipeline_analysis.md Part 5 for the real-corpus case
        (13_agent_framework) that motivated this: `deep`'s enhancement
        instances were spread thin across many sections while `standard`
        concentrated instances into one heavily-weighted section, letting
        `standard` win on weight alone.
    R_w[arm] = weighted_mean(rewards[arm] - explore[arm], weights=target_words)
               + simple_mean(explore[arm])

    For version 2/3 data (no "explore" field), falls back EXACTLY to the old
    pure target-words-weighted mean of the combined "rewards" value -- zero
    behaviour change for un-migrated section_oracle.json files.
    """
    arm_acc_rest: dict[str, float] = {a: 0.0 for a in ARMS}
    arm_acc_explore: dict[str, float] = {a: 0.0 for a in ARMS}
    total_w = 0
    n_sections = 0
    n_with_target = 0
    has_explore_field = False

    for sec_id, info in oracle_sections.items():
        rewards = info["rewards"]                          # {skip, light, standard, deep}
        explore = info.get("explore")                       # v4+ only; None for v2/v3
        feat = features_sections.get(sec_id, {})
        tw_val = feat.get("target_words")
        tw = int(tw_val) if tw_val is not None else 100   # fallback weight
        if tw_val is not None:
            n_with_target += 1
        total_w += tw
        n_sections += 1

        for arm in ARMS:
            total_reward = float(rewards.get(arm, 0.0))
            if explore is not None:
                has_explore_field = True
                explore_val = float(explore.get(arm, 0.0))
                arm_acc_rest[arm] += tw * (total_reward - explore_val)
                arm_acc_explore[arm] += explore_val
            else:
                arm_acc_rest[arm] += tw * total_reward

    if total_w == 0:
        return {a: 0.0 for a in ARMS}, 0, len(oracle_sections), n_with_target

    if has_explore_field:
        r_w = {
            a: (arm_acc_rest[a] / total_w) + (arm_acc_explore[a] / n_sections)
            for a in ARMS
        }
    else:
        r_w = {a: arm_acc_rest[a] / total_w for a in ARMS}
    return r_w, total_w, n_sections, n_with_target


def _compute_gate_diagnostics(
    oracle_sections: dict[str, dict],
) -> dict[str, dict[str, float]] | None:
    """Per-arm simple mean of cp/ra/gsp across sections (unweighted -- these
    are satisficing checks, not content-value signals). Returns None when
    section_oracle.json predates the "diagnostics" field (v<5).
    """
    sums = {a: {"cp": 0.0, "ra": 0.0, "gsp": 0.0} for a in ARMS}
    n = 0
    for info in oracle_sections.values():
        diag = info.get("diagnostics")
        if diag is None:
            return None
        n += 1
        for a in ARMS:
            for k in ("cp", "ra", "gsp"):
                sums[a][k] += diag[a][k]
    if n == 0:
        return None
    return {a: {k: round(v / n, 6) for k, v in sums[a].items()} for a in ARMS}


# ---------------------------------------------------------------------------
# Oracle decision
# ---------------------------------------------------------------------------

def _decide(
    article: str,
    r_w: dict[str, float],
    n_draws: int = 1,
    external_evidence_policy: str = "allowed",
) -> tuple[str, bool, bool, list[str], list[str]]:
    """Return (oracle_arm, manual_override, needs_review, decision_path, candidate_arms).

    Pure mean-R_w argmax (A.16, 2026-08-25) -- retires the EPS_BAND/S3/S4/S5
    near-tie tie-break entirely. ``r_w`` is expected to already be the mean
    across every available draw (production + replicates, via
    section_oracle_averaged.json when it exists); ``n_draws`` says how many
    contributed, so the confidence check can shrink ARTICLE_MARGIN_NOISE_SD
    by sqrt(n_draws) -- an averaged margin is less noisy than a single draw's.

    ``candidate_arms`` is the arm set the decision actually searched over --
    ARMS unless policy=="capped" restricts it to ["skip", "light"] (A.20) --
    so the caller's runner-up/margin bookkeeping can stay scoped to the same
    set instead of always comparing against arms the policy ruled out.
    """
    # -1. Hard constraint: forbidden policy → skip, regardless of R_w.
    #     External evidence cannot be used in the final article, so the only
    #     valid production choice is the no-exploration arm.
    if external_evidence_policy == "forbidden":
        return "skip", False, False, ["policy=forbidden → skip (hard constraint)"], ARMS

    # 0.  Manual override: absolute precedence over the mean-R_w computation.
    if article in _MANUAL_OVERRIDES:
        arm = _MANUAL_OVERRIDES[article]
        return arm, True, False, [f"manual override → {arm}"], ARMS

    # Scenario C (A.20): article's own stated scope is a survey/exploitation
    # task, not a hard ban -- cap the decision to {skip, light}, never
    # standard/deep, without forcing a single fixed answer the way forbidden does.
    candidate_arms = ["skip", "light"] if external_evidence_policy == "capped" else ARMS

    ranked = sorted(candidate_arms, key=lambda a: r_w[a], reverse=True)
    best_arm = ranked[0]
    margin = r_w[best_arm] - r_w[ranked[1]]
    threshold = ARTICLE_MARGIN_NOISE_SD / (n_draws ** 0.5)
    needs_review = margin < threshold
    path = [
        f"mean R_w argmax over {n_draws} draw(s), policy={external_evidence_policy} "
        f"(candidates={candidate_arms}): {best_arm}  "
        f"margin={margin:+.4f}  1x-noise-sd threshold={threshold:.4f}  "
        f"{'BELOW threshold, low confidence' if needs_review else 'confident'}"
    ]
    return best_arm, False, needs_review, path, candidate_arms


