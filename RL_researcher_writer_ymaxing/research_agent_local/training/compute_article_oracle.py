# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(
        description=(
            "Compute article-level oracles from section_oracle.json v2 "
            "and write article_oracle.json for all 24 training variants."
        )
    )
    parser.add_argument(
        "--article",
        type=str,
        default=None,
        metavar="NAME",
        help="Process a single article-variant (default: all 24).",
    )
    parser.add_argument(
        "--articles",
        nargs="+",
        metavar="NAME",
        help="Process one or more article-variants (space-separated).",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print results to stdout; do not write any files.",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Overwrite existing article_oracle.json files (default: skip if already present).",
    )
    parser.add_argument(
        "--bases-dir",
        type=Path,
        default=None,
        help="Override the bases root (default: production rl_training_data/bases/). "
             "Must match generate_episode_oracles.py's --bases-dir for the same experiment.",
    )
    args = parser.parse_args()

    if args.bases_dir is not None:
        global _BASES_DIR
        _BASES_DIR = args.bases_dir

    if args.articles:
        targets = args.articles
    elif args.article:
        targets = [args.article]
    else:
        targets = ALL_ARTICLES

    mode = "DRY-RUN" if args.dry_run else ("FORCE" if args.force else "WRITE")
    print(
        f"compute_article_oracle.py  [{mode}]  "
        f"4-arm scheme (skip/light/standard/deep)\n"
        f"  Targets: {len(targets)} article-variant(s)\n"
    )

    results: list[dict] = []
    errors: list[tuple[str, str]] = []

    for article in targets:
        try:
            print(f"  {article} ...", end=" ", flush=True)
            data = compute_article_oracle(article)
            results.append(data)

            flag = " ★OVERRIDE" if data["manual_override"] else ""
            flag += " ⚠REVIEW" if data["needs_review"] else ""
            flag += " ⚑LOWSIG" if data["low_signal_flag"] else ""
            r_w_str = "  ".join(
                f"{a}={data['r_w_rewards'][a]:.3f}" for a in ARMS
            )
            print(
                f"oracle={data['oracle_arm']:<8}  "
                f"margin={data['margin']:+.4f}  "
                f"R_w=[{r_w_str}]{flag}"
            )

            if not args.dry_run:
                out_path = _BASES_DIR / article / "article_oracle.json"
                if out_path.exists() and not args.force:
                    print(f"  SKIP (already exists; use --force to overwrite): {out_path.name}")
                else:
                    out_path.write_text(
                        json.dumps(data, indent=2), encoding="utf-8"
                    )

        except Exception as exc:
            print(f"  ERROR: {exc}")
            errors.append((article, str(exc)))

    # --- summary table ---
    if results:
        col_w = max(len(d["article"]) for d in results) + 2
        print()
        print(
            f"  {'Article':<{col_w}}  {'Oracle':>8}  "
            f"{'Margin':>8}  Decision"
        )
        print("  " + "-" * (col_w + 60))
        for d in results:
            flags = " ★" if d["manual_override"] else "  "
            flags += "⚠" if d["needs_review"] else " "
            flags += "⚑" if d["low_signal_flag"] else " "
            path0 = d["decision_path"][0][:60] if d["decision_path"] else ""
            print(
                f"  {d['article']:<{col_w}}  "
                f"{d['oracle_arm']:<8}  "
                f"{d['margin']:>+8.4f}  "
                f"{path0}{flags}"
            )

    if not args.dry_run and results:
        print(
            f"\n  Wrote {len(results)} article_oracle.json file(s) "
            f"under rl_training_data/bases/{'  (--force active)' if args.force else ''}"
        )

    if errors:
        print(f"\n  {len(errors)} ERROR(s):")
        for art, msg in errors:
            print(f"    {art}: {msg}")
        sys.exit(1)


if __name__ == "__main__":
    main()
